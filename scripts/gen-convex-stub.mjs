#!/usr/bin/env node
// Generates a minimal Convex `_generated/` stub so tests + typecheck work
// without needing `npx convex dev` (which requires Convex cloud login).
//
// The real `npx convex dev` writes richer files with the same shape. Our
// stub is idempotent:
//   - If `api.d.ts` already exists and does NOT contain the stub marker, the
//     script assumes the real codegen has run and exits without writing.
//   - With `--force`, overwrites unconditionally.
//
// This is intended as a dev-loop convenience only. CI should run real
// codegen via a provisioned CONVEX_DEPLOY_KEY.

import { readdirSync, mkdirSync, writeFileSync, statSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const FORCE = process.argv.includes('--force')

const convexDir = fileURLToPath(new URL('../convex/', import.meta.url)).replace(/[\\/]$/, '')
const generatedDir = join(convexDir, '_generated')
mkdirSync(generatedDir, { recursive: true })

// Skip files that never contribute function references (schema tables, config).
const SKIP_FILE_NAMES = new Set(['schema.ts', 'auth.config.ts', 'tsconfig.json', 'README.md', '.gitignore'])
// Skip top-level directories that hold tests or generated code.
const SKIP_DIR_NAMES = new Set(['_generated', 'tests'])

/** @returns {string[]} module paths (relative to convex/, no extension) */
function collectModules() {
  const modules = []
  function walk(dir, prefix) {
    for (const entry of readdirSync(dir)) {
      if (entry.startsWith('.') || entry.startsWith('_')) continue
      const full = join(dir, entry)
      const st = statSync(full)
      if (st.isDirectory()) {
        if (prefix === '' && SKIP_DIR_NAMES.has(entry)) continue
        walk(full, prefix ? `${prefix}/${entry}` : entry)
      } else if (entry.endsWith('.ts') && !entry.endsWith('.test.ts')) {
        if (SKIP_FILE_NAMES.has(entry)) continue
        const rel = prefix ? `${prefix}/${entry.replace(/\.ts$/, '')}` : entry.replace(/\.ts$/, '')
        modules.push(rel)
      }
    }
  }
  walk(convexDir, '')
  return modules.sort()
}

const modules = collectModules()

const importLines = modules
  .map((m) => {
    const varName = m.replace(/[/.-]/g, '_')
    return `import type * as ${varName} from "../${m}.js";`
  })
  .join('\n')

const moduleMapEntries = modules.map((m) => `  "${m}": typeof ${m.replace(/[/.-]/g, '_')};`).join('\n')

const apiDts = `/* eslint-disable */
/**
 * Generated \`api\` utility.
 *
 * NOTE: This file is a stub generated by scripts/gen-convex-stub.mjs. The real
 * Convex codegen (\`npx convex dev\`) will replace it with the same shape once
 * a Convex deployment is configured.
 */
import type { ApiFromModules, FilterApi, FunctionReference } from "convex/server";
${importLines}

declare const fullApi: ApiFromModules<{
${moduleMapEntries}
}>;

export declare const api: FilterApi<typeof fullApi, FunctionReference<any, "public">>;
export declare const internal: FilterApi<typeof fullApi, FunctionReference<any, "internal">>;
export declare const components: Record<string, never>;
`

const apiJs = `/* eslint-disable */
import { anyApi } from "convex/server";
export const api = anyApi;
export const internal = anyApi;
export const components = {};
`

const dataModelDts = `/* eslint-disable */
import type { DataModelFromSchemaDefinition, DocumentByName } from "convex/server";
import type { GenericId } from "convex/values";
import type schema from "../schema.js";

export type DataModel = DataModelFromSchemaDefinition<typeof schema>;

export type TableNames = keyof DataModel;

export type Doc<TableName extends TableNames> = DocumentByName<DataModel, TableName>;

export type Id<TableName extends TableNames | string = TableNames> = GenericId<TableName>;
`

const serverDts = `/* eslint-disable */
import type {
  ActionBuilder,
  HttpActionBuilder,
  MutationBuilder,
  QueryBuilder,
  GenericActionCtx,
  GenericMutationCtx,
  GenericQueryCtx,
} from "convex/server";
import type { DataModel } from "./dataModel.js";

export declare const query: QueryBuilder<DataModel, "public">;
export declare const internalQuery: QueryBuilder<DataModel, "internal">;
export declare const mutation: MutationBuilder<DataModel, "public">;
export declare const internalMutation: MutationBuilder<DataModel, "internal">;
export declare const action: ActionBuilder<DataModel, "public">;
export declare const internalAction: ActionBuilder<DataModel, "internal">;
export declare const httpAction: HttpActionBuilder;

export type QueryCtx = GenericQueryCtx<DataModel>;
export type MutationCtx = GenericMutationCtx<DataModel>;
export type ActionCtx = GenericActionCtx<DataModel>;
`

const serverJs = `/* eslint-disable */
import {
  actionGeneric,
  httpActionGeneric,
  internalActionGeneric,
  internalMutationGeneric,
  internalQueryGeneric,
  mutationGeneric,
  queryGeneric,
} from "convex/server";

export const query = queryGeneric;
export const internalQuery = internalQueryGeneric;
export const mutation = mutationGeneric;
export const internalMutation = internalMutationGeneric;
export const action = actionGeneric;
export const internalAction = internalActionGeneric;
export const httpAction = httpActionGeneric;
`

const STUB_MARKER = 'NOTE: This file is a stub generated by scripts/gen-convex-stub.mjs'

function isStubOrMissing(path) {
  if (!existsSync(path)) return true
  try {
    return readFileSync(path, 'utf8').includes(STUB_MARKER)
  } catch {
    return true
  }
}

const files = [
  ['api.d.ts', apiDts],
  ['api.js', apiJs],
  ['dataModel.d.ts', dataModelDts],
  ['server.d.ts', serverDts],
  ['server.js', serverJs],
]

const apiPath = join(generatedDir, 'api.d.ts')
if (!FORCE && existsSync(apiPath) && !isStubOrMissing(apiPath)) {
  console.log('Real Convex _generated/ detected; leaving it in place.')
  console.log('(Use --force to overwrite with stubs.)')
  process.exit(0)
}

for (const [name, content] of files) {
  writeFileSync(join(generatedDir, name), content)
}

console.log(`Generated _generated/ stub for ${modules.length} modules:`)
for (const m of modules) console.log('  -', m)
